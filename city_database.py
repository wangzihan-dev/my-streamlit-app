def get_city_names():
    """返回数据库中已有攻略的城市名称列表。"""
    return list(CITY_DATABASE.keys())


def get_city_guide(city: str):
    """
    按城市名获取攻略字典；若不存在则返回 None。
    参数：
        city: 城市名，如「北京」「成都」
    """
    return CITY_DATABASE.get(city)


def list_attraction_names(city: str):
    """返回某城市全部景点名称列表，供 UI 联想或校验。"""
    g = CITY_DATABASE.get(city)
    if not g:
        return []
    return [x.get("名称", "") for x in g.get("景点", [])]


def iter_all_attractions():
    """遍历全库 (城市名, 景点字典)。"""
    for cname, data in CITY_DATABASE.items():
        for spot in data.get("景点", []):
            yield cname, spot


def _norm(s: str) -> str:
    return (s or "").strip().replace(" ", "")


def lookup_attraction(city_hint: str | None, name: str) -> dict | None:
    """
    按景点名查找条目；可限定城市，也可全库模糊匹配。
    返回字典在命中时会附加键 \"_matched_city\" 表示所属城市。
    参数：
        city_hint: 城市名；None 或 \"自动（全库匹配）\" 表示不限定城市。
        name: 用户输入的景点名（可含别名）。
    """
    raw = _norm(name)
    if not raw:
        return None

    auto = city_hint in (None, "", "自动（全库匹配）")

    def try_city(c):
        data = CITY_DATABASE.get(c)
        if not data:
            return None
        for spot in data.get("景点", []):
            sn = _norm(spot.get("名称", ""))
            if not sn:
                continue
            if raw == sn or raw in sn or sn in raw:
                out = dict(spot)
                out["_matched_city"] = c
                return out
        return None

    if not auto and city_hint:
        hit = try_city(city_hint)
        if hit:
            return hit

    for c in CITY_DATABASE:
        hit = try_city(c)
        if hit:
            return hit
    return None
